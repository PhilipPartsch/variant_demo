"""Import the CTest results of every product as `test_result` needs.

Usage: import_test_results.py [--site build/site] [--output docs/_global/test_results.rst]

Reads, per product, build/site/<product>/junit.xml (`ctest --output-junit`,
written by tools/build_product.sh) and the product's ubc needs export. Each
test executable prints one line per test case: "PASS <TEST id>" or
"FAIL <TEST id>", so the mapping to the `test` need is by id, not heuristic.

Writes one `test_result` per test need and product, inside an `if` block for
that product (results are evidence of one product, B§4.3):
  TRES_<test id without TEST_>__<PRODUCT>, results_for the test,
  fields outcome, runtime_s, test_run_label, chain_reqs, product.
The output is a committed snapshot; re-run after tools/build_all.sh.
"""
import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINE = re.compile(r"^(PASS|FAIL) (TEST_[A-Z][A-Z0-9_]*)$", re.M)


def needs_of(export: Path) -> dict:
    d = json.loads(export.read_text())
    v = d["versions"]
    return v[d.get("current_version") or next(iter(v))]["needs"]


def chain(test: dict, needs: dict) -> list[str]:
    """test -> verifies swreq -> refines arch -> satisfies req."""
    reqs = set()
    for sw in test.get("verifies") or []:
        for arch in needs.get(sw, {}).get("refines") or []:
            reqs.update(needs.get(arch, {}).get("satisfies") or [])
    return sorted(reqs)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--site", type=Path, default=ROOT / "build/site")
    ap.add_argument("--output", type=Path, default=ROOT / "docs/_global/test_results.rst")
    args = ap.parse_args()
    out = [
        "Test results",
        "============",
        "",
        "Test results (``test_result``) of each product, generated by",
        "``tools/import_test_results.py`` from the CTest run of",
        "``tools/build_product.sh``. Only the results of this build's product",
        "(:variant:`meta.product`) are shown.",
        "",
        ".. needtable::",
        "   :types: test_result",
        "   :columns: id, outcome, results_for, chain_reqs, test_run_label",
        "   :style: table",
    ]
    errors = []
    for site in sorted(p for p in args.site.iterdir() if (p / "junit.xml").exists()):
        product = site.name
        needs = needs_of(site / "ubc.needs.json")
        suite = ET.parse(site / "junit.xml").getroot()
        stamp = datetime.fromisoformat(suite.get("timestamp")).strftime("%Y-%m-%d %H:%M:%S")
        block = []
        for case in suite.iter("testcase"):
            text = case.findtext("system-out") or ""
            for outcome, test_id in LINE.findall(text):
                test = needs.get(test_id)
                if test is None or test.get("type") != "test":
                    errors.append(f"{product}: {test_id} printed by {case.get('name')} is not a test need")
                    continue
                reqs = chain(test, needs)
                block += [
                    "",
                    f"   .. test_result:: {test['title']} ({product})",
                    f"      :id: TRES_{test_id.removeprefix('TEST_')}__{product.upper()}",
                    f"      :results_for: {test_id}",
                    f"      :outcome: {'passed' if outcome == 'PASS' else 'failed'}",
                    f"      :runtime_s: {float(case.get('time', 0)):.3f}",
                    f"      :test_run_label: {stamp}",
                    f"      :chain_reqs: {', '.join(reqs)}",
                    f"      :product: {product}",
                    "",
                    f"      ``{case.get('name')}`` reported {outcome} for {test_id}.",
                ]
        tests = {i for i, n in needs.items() if n.get("type") == "test" and not i.startswith("BMS_")}
        reported = {t for c in suite.iter("testcase") for _, t in LINE.findall(c.findtext("system-out") or "")}
        missing = tests - reported
        if missing:
            errors.append(f"{product}: test needs without a result: {sorted(missing)}")
        out += ["", f".. if:: var.meta.product == '{product}'", *block]
    for e in errors:
        print(f"import_test_results: {e}", file=sys.stderr)
    if errors:
        return 1
    args.output.write_text("\n".join(out) + "\n")
    print(f"import_test_results: wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
